package lombok;

import lombok.core.configuration.ConfigurationKey;
import lombok.core.configuration.ConfigurationKeysLoader;

/**
 * Configuration keys for {@link OptionalGetter}. Registered through lombok's {@code ConfigurationKeysLoader}
 * SPI (see {@code META-INF/services/lombok.core.configuration.ConfigurationKeysLoader}) so the key is
 * recognised in {@code lombok.config}.
 */
public final class OptionalGetterConfigurationKeys implements ConfigurationKeysLoader {

	/**
	 * {@code lombok.optionalGetter.suffix} = &lt;text&gt; (default {@code Optional}).
	 * <p>
	 * Suffix appended to the accessor name that {@code @OptionalGetter} generates. With the default, a field
	 * {@code foo} yields {@code getFooOptional()}; set the key to an empty value to get {@code getFoo()} instead.
	 */
	public static final ConfigurationKey<String> OPTIONAL_GETTER_SUFFIX = new ConfigurationKey<String>(
		"lombok.optionalGetter.suffix",
		"Suffix appended to the accessor name generated by @OptionalGetter (default: Optional).") {};

	/** Default suffix, applied when the key is not set in lombok.config. */
	public static final String DEFAULT_SUFFIX = "Optional";
}
